import { Check, Copy, Download, Loader2, Upload } from "lucide-react";
import { useEffect, useMemo, useState } from "react";
import { Link } from "react-router-dom";
import { PageHeader } from "@/components/layout/AppShell";
import { Card } from "@/components/ui/Card";
import { Button, buttonClass } from "@/components/ui/Button";
import { useToast } from "@/components/ui/Toast";
import { api, ApiError } from "@/lib/api";
import { bytesOf, fileStem, formatBytes, truncate } from "@/lib/format";
import { useWorkspace } from "@/lib/workspace";

type BackendFormat = "json" | "txt" | "markdown";
type UiFormat = BackendFormat | "pdf";

const SECTIONS = [
  { id: "transcript", label: "Transcript" },
  { id: "summary", label: "AI Summary" },
  { id: "topics", label: "Key Topics" },
  { id: "speakers", label: "Speaker Segments" },
  { id: "sentiment", label: "Sentiment & Insights" },
] as const;

export function ExportPage() {
  const { recordings, selectedId, setSelectedId } = useWorkspace();
  const { push } = useToast();

  const [uiFormat, setUiFormat] = useState<UiFormat>("json");
  const [selectedSections, setSelectedSections] = useState<Record<string, boolean>>({
    transcript: true,
    summary: true,
    topics: true,
    speakers: true,
    sentiment: true,
  });
  const [preview, setPreview] = useState<{ content: string; filename: string } | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);

  const recording = useMemo(
    () => recordings.find((item) => item.id === selectedId) ?? recordings[0] ?? null,
    [recordings, selectedId],
  );
  const id = recording?.id ?? null;

  const backendFormat: BackendFormat = uiFormat === "pdf" ? "markdown" : uiFormat;

  useEffect(() => {
    if (!id) {
      setPreview(null);
      return;
    }
    let cancelled = false;
    setLoading(true);
    setError(null);
    setCopied(false);

    api
      .export(id, backendFormat)
      .then((result) => {
        if (!cancelled) setPreview(result);
      })
      .catch((err: unknown) => {
        if (cancelled) return;
        setPreview(null);
        setError(err instanceof ApiError ? err.message : "Export failed.");
      })
      .finally(() => {
        if (!cancelled) setLoading(false);
      });

    return () => {
      cancelled = true;
    };
  }, [id, backendFormat]);

  function toggleSection(key: string) {
    setSelectedSections((prev) => ({ ...prev, [key]: !prev[key] }));
  }

  async function handleCopy() {
    if (!preview) return;
    try {
      await navigator.clipboard.writeText(preview.content);
      setCopied(true);
      push("Export copied to clipboard.", "success");
      window.setTimeout(() => setCopied(false), 2000);
    } catch {
      push("Clipboard access was denied.", "error");
    }
  }

  function handleDownload() {
    if (!preview) return;
    if (uiFormat === "pdf") {
      push(
        "PDF export is not natively generated by the backend. Downloading Markdown report instead.",
        "info",
      );
    }
    const mime =
      backendFormat === "json"
        ? "application/json"
        : backendFormat === "markdown"
          ? "text/markdown"
          : "text/plain";
    const blob = new Blob([preview.content], { type: `${mime};charset=utf-8` });
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement("a");
    anchor.href = url;
    anchor.download = preview.filename;
    document.body.appendChild(anchor);
    anchor.click();
    anchor.remove();
    URL.revokeObjectURL(url);
    push(`Downloaded ${preview.filename}.`, "success");
  }

  return (
    <div className="space-y-4">
      <PageHeader
        crumb="WORKSPACE / EXPORT"
        title="Export Center"
        subtitle="Download transcripts, summaries, and analysis reports."
        actions={
          recordings.length > 0 ? (
            <select
              value={id ?? ""}
              onChange={(e) => setSelectedId(e.target.value)}
              aria-label="Select recording to export"
              className="h-10 rounded-[10px] border border-navy-600 bg-navy-800 px-3 text-[12px] font-medium text-ink outline-none focus:border-violet-900"
            >
              {recordings.map((r) => (
                <option key={r.id} value={r.id}>
                  {fileStem(r.original_filename)} ({r.processing_status})
                </option>
              ))}
            </select>
          ) : undefined
        }
      />

      {recordings.length === 0 ? (
        <Card className="px-6 py-14 text-center">
          <p className="text-[15px] font-semibold text-ink">Nothing to export yet</p>
          <p className="mt-1.5 text-[12px] text-mute">
            Upload and process a recording first to export its transcript and analysis.
          </p>
          <Link to="/upload" className={`${buttonClass({ size: "md" })} mt-5`}>
            <Upload className="size-4" />
            Upload Audio
          </Link>
        </Card>
      ) : (
        <>
          <div className="grid gap-4 md:grid-cols-2">
            {/* Choose Sections Card */}
            <Card className="p-5">
              <h2 className="text-[13px] font-semibold text-ink">Choose Sections</h2>

              <ul className="mt-4 space-y-2.5">
                {SECTIONS.map((sec) => {
                  const checked = selectedSections[sec.id] ?? true;
                  return (
                    <li key={sec.id}>
                      <label className="flex cursor-pointer items-center gap-3 text-[12px] text-ink">
                        <input
                          type="checkbox"
                          checked={checked}
                          onChange={() => toggleSection(sec.id)}
                          className="size-4 rounded accent-violet-600"
                        />
                        <span>{sec.label}</span>
                      </label>
                    </li>
                  );
                })}
              </ul>

              <p className="mt-4 text-[10px] text-mute/80">
                Note: Section checkboxes are a UI placeholder. The backend export endpoint (`GET /api/v1/recordings/&#123;id&#125;/export`) always includes all available sections.
              </p>
            </Card>

            {/* Output Format Card */}
            <Card className="p-5">
              <h2 className="text-[13px] font-semibold text-ink">Output Format</h2>

              <div className="mt-4 grid grid-cols-2 gap-3">
                {(
                  [
                    { value: "json", label: "JSON", supported: true, desc: "Structured data" },
                    { value: "txt", label: "TXT", supported: true, desc: "Plain text" },
                    { value: "markdown", label: "Markdown", supported: true, desc: "Formatted .md" },
                    { value: "pdf", label: "PDF", supported: false, desc: "Placeholder" },
                  ] as const
                ).map((item) => {
                  const active = uiFormat === item.value;
                  return (
                    <button
                      key={item.value}
                      type="button"
                      onClick={() => setUiFormat(item.value)}
                      className={`rounded-[11px] border p-3.5 text-left transition ${
                        active
                          ? "border-violet-500 bg-violet-800/35 shadow-[0_0_0_1px_rgba(105,59,255,0.3)]"
                          : "border-navy-600 bg-navy-800/60 hover:border-violet-900"
                      }`}
                    >
                      <div className="flex items-center justify-between">
                        <span className="text-[13px] font-bold text-ink">{item.label}</span>
                        {!item.supported && (
                          <span className="rounded bg-amber-400/15 px-1.5 py-0.5 text-[9px] font-semibold text-amber-200">
                            Placeholder
                          </span>
                        )}
                      </div>
                      <p className="mt-1 text-[10.5px] text-mute">{item.desc}</p>
                    </button>
                  );
                })}
              </div>
            </Card>
          </div>

          {/* Export Preview Card */}
          <Card className="p-5">
            <div className="flex flex-wrap items-center justify-between gap-3">
              <div>
                <h2 className="text-[13px] font-semibold text-ink">Export Preview</h2>
                <p className="mt-1 text-[11.5px] text-mute2">
                  {recording?.original_filename} &nbsp;·&nbsp;{" "}
                  {loading
                    ? "Building export preview…"
                    : preview
                      ? `Ready to export (${formatBytes(bytesOf(preview.content))})`
                      : "Unavailable"}
                </p>
              </div>

              <div className="flex items-center gap-2">
                <Button variant="ghost" size="sm" onClick={() => void handleCopy()} disabled={!preview}>
                  {copied ? <Check className="size-3.5" /> : <Copy className="size-3.5" />}
                  {copied ? "Copied" : "Copy"}
                </Button>
              </div>
            </div>

            <div className="mt-4 rounded-[11px] border border-navy-600 bg-navy-900/70 p-4">
              {loading ? (
                <div className="flex items-center gap-2 py-8 text-[12px] text-mute">
                  <Loader2 className="size-4 animate-spin" />
                  Generating {backendFormat.toUpperCase()} export from backend…
                </div>
              ) : error ? (
                <p className="py-4 text-[12px] text-rose-300">{error}</p>
              ) : preview ? (
                <pre
                  dir="auto"
                  className="scrollbar-thin max-h-[280px] overflow-auto whitespace-pre-wrap break-words font-mono text-[11px] leading-[1.7] text-mute2"
                >
                  {truncate(preview.content, 16000)}
                </pre>
              ) : (
                <p className="py-4 text-[12px] text-mute">Select a recording to preview export.</p>
              )}
            </div>

            <div className="mt-4 flex justify-end">
              <Button onClick={handleDownload} disabled={!preview || loading}>
                <Download className="size-4" />
                Download Export
              </Button>
            </div>
          </Card>
        </>
      )}
    </div>
  );
}
